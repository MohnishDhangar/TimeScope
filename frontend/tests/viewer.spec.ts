test('playback advances frames, pause stops it, and stepping wraps',async({page})=>{
 await page.goto('http://127.0.0.1:8000?session=23577cd786a24f24bedec59e7c5366ae')
 const timeline=page.getByLabel('Observation timeline')
 const image=page.getByRole('img',{name:/Current: SPHEREx/})
 await expect(image).toBeVisible()
 const initial=await image.getAttribute('src')
 await page.getByLabel('Playback speed',{exact:true}).selectOption('1200')
 await page.getByRole('button',{name:'Play',exact:true}).click()
 await expect(image).not.toHaveAttribute('src',initial!,{timeout:3000})
 await page.getByRole('button',{name:'Pause',exact:true}).click()
 const paused=await image.getAttribute('src')
 // Wait longer than one playback interval to establish that Pause actually stops the timer.
 await page.waitForTimeout(1400)
 await expect(image).toHaveAttribute('src',paused!)
 await timeline.fill('0')
 await page.getByRole('button',{name:'Previous frame',exact:true}).click()
 await expect(timeline).toHaveValue('5')
 await page.getByRole('button',{name:'Next frame',exact:true}).click()
 await expect(timeline).toHaveValue('0')
})

